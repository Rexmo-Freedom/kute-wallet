// Real Gamma events of the special shapes the market page draws, trimmed
// to the keys the app reads: each event read from Gamma by its slug (the
// app's route, `/events/slug/{slug}`, answers the same event object) on
// 2026-11-04 (the day after the 2026 midterms). Titles, prices,
// quotes, last trades and the open / closed flags are Gamma's own; ids and
// token ids are shortened, questions left out.

/// One market of an event: Yes / No tokens `<prefix><i>y` / `<prefix><i>n`.
Map<String, dynamic> specialMarket(String prefix, int i, String title,
        String? prices,
        {double? bid,
        double? ask,
        double? last,
        double? spread,
        bool closed = false,
        bool active = true,
        bool accepting = true,
        String? question}) =>
    {
      'id': '$prefix$i',
      'question': question ?? title,
      'groupItemTitle': title,
      'conditionId': '0x$prefix$i',
      'outcomes': '["Yes", "No"]',
      'outcomePrices': prices,
      'clobTokenIds': '["$prefix${i}y", "$prefix${i}n"]',
      if (bid != null) 'bestBid': bid,
      if (ask != null) 'bestAsk': ask,
      if (last != null) 'lastTradePrice': last,
      if (spread != null) 'spread': spread,
      'active': active,
      'closed': closed,
      'acceptingOrders': accepting,
      'negRisk': true,
    };

